@lru_cache(maxsize=2048)
def ascii_char(char: str) -> str:
    """Return one safe ASCII cell, transliterating Unicode when practical.

    A wide character's empty continuation cell stays blank. Combining marks
    attached by the terminal emulator are discarded after the base letter.
    Control codes are rendered as question marks rather than emitted.
    """
    if not char:
        return " "
    first = char[0]
    if " " <= first <= "~":
        return first
    if first in _SUBSTITUTIONS:
        return _SUBSTITUTIONS[first]
    if "\u2500" <= first <= "\u257f":
        return "+"
    normalized = unicodedata.normalize("NFKD", char)
    for item in normalized:
        if " " <= item <= "~":
            return item
        if not unicodedata.combining(item):
            break
    return "?"


def glyph(char: str) -> tuple[str, ...]:
    """Return seven five-bit rows for a character, with a safe fallback."""
    return _GLYPHS[ascii_char(char)]
